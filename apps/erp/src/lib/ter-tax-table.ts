const TER_TABLES: Record<"A" | "B" | "C", [number, number | null, number][]> = {
  A: TER_A,
  B: TER_B,
  C: TER_C,
};

/** Cari tarif TER buat sebuah nominal Penghasilan Bruto Bulanan, dalam satu kategori (A/B/C). */
function findTerRate(category: "A" | "B" | "C", grossMonthly: number): number {
  const table = TER_TABLES[category];
  for (const [lo, hi, rate] of table) {
    if (grossMonthly >= lo && (hi === null || grossMonthly <= hi)) return rate;
  }
  return table[table.length - 1][2];
}

/**
 * Hitung PPh21 bulanan pakai metode TER: PTKP -> kategori TER (A/B/C) -> cari
 * tarif dari Penghasilan Bruto Bulanan -> PPh21 = Bruto x Tarif.
 */
export function calculatePph21Ter(ptkpCode: string, grossMonthlyBruto: number): { category: "A" | "B" | "C" | null; rate: number; pph21: number } {
  const category = PTKP_TO_TER_CATEGORY[ptkpCode] ?? null;
  if (!category || grossMonthlyBruto <= 0) return { category: null, rate: 0, pph21: 0 };
  const rate = findTerRate(category, grossMonthlyBruto);
  return { category, rate, pph21: Math.round(grossMonthlyBruto * rate) };
}
